#!/usr/bin/env python3
"""Generate complete static language editions from Korean pages and reviewed translations."""
from __future__ import annotations
import argparse
import json
import re
import sys
from html import escape
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urljoin, urlsplit, urlunsplit
import xml.etree.ElementTree as ET

from i18n_catalog import (ROOT, PAGES, TEXT_ATTRIBUTES, META_NAMES, SVG_SOURCE,
                          normalize, string_id, is_text, strip_managed, shared_guide_header)

BASE = 'https://k-remedi.com'
LOCALES = {
    'ko': {'html': 'ko', 'hreflang': 'ko', 'og': 'ko_KR', 'label': '한국어'},
    'en': {'html': 'en', 'hreflang': 'en', 'og': 'en_US', 'label': 'English'},
    'zh': {'html': 'zh-Hans', 'hreflang': 'zh-Hans', 'og': 'zh_CN', 'label': '简体中文'},
    'ja': {'html': 'ja', 'hreflang': 'ja', 'og': 'ja_JP', 'label': '日本語'},
}
MARKER = '<!-- Generated by scripts/build_i18n.py; edit Korean sources and content/i18n. -->'
SCRIPT_VERSION = '20261109-languages'
COUNT_TEMPLATE = '{selected} / {total}개 선택'
EXTERNAL_NOTE = '예약 서비스와 지도는 외부 사이트에서 열립니다. 연결된 서비스는 한국어로 표시될 수 있습니다.'

def route(name: str, locale: str) -> str:
    path = '/' if name == 'index.html' else '/' + name.removesuffix('.html')
    return path if locale == 'ko' else '/' + locale + path

PAGE_BY_ROUTE = {route(name, 'ko'): name for name in PAGES}

def read(path: Path) -> str:
    value = path.read_bytes().decode('utf-8')
    if '\ufffd' in value:
        raise ValueError(f'Invalid replacement character: {path}')
    return value

def attribute(raw: str, key: str, value: str | None) -> str:
    pattern = r'(\s+' + re.escape(key) + r')(?:\s*=\s*("[^"]*"|\x27[^\x27]*\x27|[^\s>]+))?(?=\s|/?>)'
    match = re.search(pattern, raw)
    replacement = '' if value is None else ' ' + key + '="' + escape(value, quote=True) + '"'
    if match:
        return raw[:match.start()] + replacement + raw[match.end():]
    if value is None:
        return raw
    return re.sub(r'\s*(/?>)$', lambda m: replacement + (' />' if m[1] == '/>' else '>'), raw)

class Dictionary:
    def __init__(self, locale: str):
        self.locale = locale
        self.values = {} if locale == 'ko' else json.loads(read(ROOT/f'content/i18n/{locale}.json'))
        if not isinstance(self.values, dict):
            raise ValueError(f'{locale}: translations must be an object')

    def get(self, source: str) -> str:
        source = normalize(source)
        if self.locale == 'ko' or not is_text(source):
            return source
        key = string_id(source)
        value = self.values.get(key)
        if not isinstance(value, str) or not value.strip() or '\ufffd' in value:
            raise ValueError(f'{self.locale}: missing translation {key}: {source[:100]}')
        if re.findall(r'\{\w+\}', source) != re.findall(r'\{\w+\}', value):
            # Placeholder order may naturally change between languages.
            if sorted(re.findall(r'\{\w+\}', source)) != sorted(re.findall(r'\{\w+\}', value)):
                raise ValueError(f'{self.locale}: changed placeholders for {key}')
        return value

def local_url(value: str, source: str, locale: str) -> str:
    if not value or value.startswith('#'):
        return value
    parsed = urlsplit(value)
    if parsed.scheme and parsed.scheme not in ('http', 'https'):
        return value
    resolved = urlsplit(urljoin(BASE + '/' + source, value))
    if resolved.netloc not in ('k-remedi.com', 'www.k-remedi.com'):
        return value
    path = resolved.path
    if path.endswith('/index.html'):
        path = path[:-10]
    elif path.endswith('.html'):
        path = path[:-5]
    if path in PAGE_BY_ROUTE:
        path = route(PAGE_BY_ROUTE[path], locale)
    elif path == '/' + SVG_SOURCE and locale != 'ko':
        path = f'/assets/i18n/{locale}/photo-direction.svg'
    query = resolved.query
    if path in ('/script.js', '/asymmetry.js'):
        query = 'v=' + SCRIPT_VERSION
    absolute = bool(parsed.scheme or parsed.netloc)
    return urlunsplit(('https' if absolute else '', 'k-remedi.com' if absolute else '', path, query, resolved.fragment))

class Translator(HTMLParser):
    def __init__(self, source: str, locale: str, dictionary: Dictionary):
        super().__init__(convert_charrefs=False)
        self.source, self.locale, self.dictionary = source, locale, dictionary
        self.output = []
        self.blocked = None
        self.kind = None
        self.buffer = ''
        self.option = False

    def schema(self, value, key='', entity_type=None):
        if isinstance(value, dict):
            kind = value.get('@type', entity_type)
            return {k: self.schema(v, k, kind) for k, v in value.items()}
        if key == 'alternateName':
            return value  # Keep the clinic's real Korean names and aliases intact.
        if isinstance(value, list):
            return [self.schema(v, key, entity_type) for v in value]
        if not isinstance(value, str):
            return value
        if key == 'inLanguage':
            return LOCALES[self.locale]['html']
        if value.startswith(BASE):
            if value in (BASE+'/#clinic', BASE+'/#website') or (key == 'url' and entity_type in ('MedicalClinic', 'WebSite')):
                return value
            return local_url(value, self.source, self.locale)
        if re.search(r'[\uac00-\ud7a3]', value):
            return self.dictionary.get(value)
        return value

    def start(self, tag, attrs):
        raw = self.get_starttag_text()
        data = dict(attrs)
        if tag == 'html':
            raw = attribute(raw, 'lang', LOCALES[self.locale]['html'])
        for key, value in attrs:
            if value is None:
                continue
            if key in TEXT_ATTRIBUTES:
                raw = attribute(raw, key, self.dictionary.get(value))
            elif key in ('href', 'src'):
                target = 'tel:+82269511075' if value == 'tel:0269511075' else local_url(value, self.source, self.locale)
                raw = attribute(raw, key, target)
        if tag == 'meta':
            label = data.get('name') or data.get('property')
            if label in META_NAMES:
                raw = attribute(raw, 'content', self.dictionary.get(data['content']))
            elif label == 'og:locale':
                raw = attribute(raw, 'content', LOCALES[self.locale]['og'])
            elif label == 'og:url':
                raw = attribute(raw, 'content', BASE+route(self.source, self.locale))
        if tag in ('script', 'style'):
            self.blocked, self.kind, self.buffer = tag, data.get('type'), ''
        if tag == 'option':
            self.option = True
        self.output.append(raw)

    handle_starttag = start
    handle_startendtag = start

    def handle_endtag(self, tag):
        if tag == self.blocked:
            if tag == 'script' and self.kind == 'application/ld+json':
                transformed = self.schema(json.loads(self.buffer))
                self.output.append('\n'+json.dumps(transformed, ensure_ascii=False, indent=2).replace('<', '\\u003c')+'\n')
            else:
                self.output.append(self.buffer)
            self.blocked = None
        self.output.append('</' + tag + '>')
        if tag == 'option':
            self.option = False

    def handle_data(self, text):
        if self.blocked:
            self.buffer += text
        elif normalize(text) == '02-6951-1075':
            self.output.append(text.replace('02-6951-1075', '+82 2-6951-1075'))
        elif self.option or not normalize(text) or not is_text(normalize(text)):
            self.output.append(text)
        else:
            start = re.match(r'\s*', text)[0]
            end = re.search(r'\s*$', text)[0]
            self.output.append(start + escape(self.dictionary.get(text), quote=False) + end)

    def handle_entityref(self, name): self.output.append('&' + name + ';')
    def handle_charref(self, name): self.output.append('&#' + name + ';')
    def handle_comment(self, data): self.output.append('<!--' + data + '-->')
    def handle_decl(self, data): self.output.append('<!' + data + '>')
    def handle_pi(self, data): self.output.append('<?' + data + '>')

def enhance(text: str, name: str, locale: str, dictionary: Dictionary) -> str:
    text = strip_managed(text)
    newline = '\r\n' if text.count('\r\n') > text.count('\n') / 2 else '\n'
    alternates = [f'    <link rel="alternate" hreflang="{info["hreflang"]}" href="{BASE}{route(name, code)}" />' for code, info in LOCALES.items()]
    alternates.append(f'    <link rel="alternate" hreflang="x-default" href="{BASE}{route(name, "ko")}" />')
    head = ['    <!-- i18n:head -->', *alternates, '    <link rel="stylesheet" href="/i18n.css?v=20261109-languages" />', '    <!-- /i18n -->']
    text = re.sub(r'(?m)^([ \t]*)</head>', lambda m: newline.join(head)+newline+m[0], text, count=1)
    select = re.search(r'<select\b[^>]*\bid="language-select"[^>]*>.*?</select>', text, re.S)
    if not select:
        raise ValueError(f'{name}: language selector is missing')
    control = select[0]
    opening = control[:control.index('>')+1]
    new_opening = opening
    for code in LOCALES:
        new_opening = attribute(new_opening, 'data-language-' + code, route(name, code))
    control = new_opening + control[len(opening):]
    def choose(match):
        option = re.sub(r'\s+selected(?:="[^"]*")?', '', match[0])
        code = re.search(r'value="([^"]+)"', option)[1]
        return attribute(option, 'selected', '' if code == locale else None)
    control = re.sub(r'<option\b[^>]*>', choose, control)
    control = re.sub(r'(<option\b[^>]*value="([^"]+)"[^>]*>)[^<]*(</option>)', lambda m: m[1]+LOCALES[m[2]]['label']+m[3], control)
    text = text[:select.start()] + control + text[select.end():]
    label = dictionary.get('언어 버전')
    links = [f'<a href="{route(name, code)}" lang="{info["html"]}" hreflang="{info["hreflang"]}"'+(' aria-current="page"' if code == locale else '')+'>'+info['label']+'</a>' for code, info in LOCALES.items()]
    footer = newline.join(['      <!-- i18n:links -->', '      <nav class="language-links" aria-label="'+escape(label, quote=True)+'">'+' · '.join(links)+'</nav>', '      <!-- /i18n -->']) + newline
    text, count = re.subn(r'(?m)^([ \t]*)<p class="footer-copy"', lambda m: footer + m[0], text, count=1)
    if count != 1:
        raise ValueError(f'{name}: footer copyright marker is missing')
    text = re.sub(r'(?<![\w-])(script|asymmetry)\.js\?v=[^"\s]+', lambda m: m[1]+'.js?v='+SCRIPT_VERSION, text)
    if name == 'asymmetry.html':
        count_text = '{total}개 중 {selected}개 선택' if locale == 'ko' else dictionary.get(COUNT_TEMPLATE)
        text = re.sub(r'<[^>]+\bdata-check-count(?=[\s>])[^>]*>', lambda m: attribute(m[0], 'data-check-count-template', count_text), text, count=1)
    if locale != 'ko' and name == 'contact.html':
        note = '<p class="language-service-note">'+escape(dictionary.get(EXTERNAL_NOTE))+'</p>'
        text = text.replace('</main>', note + '\n    </main>', 1)
    return text

def sitemap(text: str, settings: dict) -> str:
    ET.fromstring(text)
    urls = {BASE+route(name, code): settings.get('pageModified', {}).get(name, settings['published']) for code in LOCALES if code != 'ko' for name in PAGES}
    namespace = {'s': 'http://www.sitemaps.org/schemas/sitemap/0.9'}
    actual = {n.text for n in ET.fromstring(text).findall('s:url/s:loc', namespace)}
    obsolete = [url for url in actual if any(url.startswith(BASE+'/'+code+'/') for code in ('en','zh','ja')) and url not in urls]
    if obsolete:
        raise ValueError('Unmatched language URLs in sitemap: ' + ', '.join(obsolete))
    def update_entry(match):
        location = re.search(r'<loc>(.*?)</loc>', match[0])
        if location and location[1] in urls:
            return re.sub(r'<lastmod>.*?</lastmod>', '<lastmod>'+urls[location[1]]+'</lastmod>', match[0])
        return match[0]
    text = re.sub(r'<url>.*?</url>', update_entry, text, flags=re.S)
    for url in sorted(urls):
        if url not in actual:
            text = text.replace('</urlset>', f'  <url><loc>{url}</loc><lastmod>{urls[url]}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>\n</urlset>')
    return text

def build(check=False):
    sources = {name: read(ROOT/name) for name in PAGES}
    translations = {code: Dictionary(code) for code in LOCALES}
    settings = json.loads(read(ROOT/'content/i18n/settings.json'))
    outputs = {}
    for name, original in sources.items():
        outputs[ROOT/name] = enhance(original, name, 'ko', translations['ko']).encode('utf-8')
        for code in ('en', 'zh', 'ja'):
            source = strip_managed(original)
            if name == 'asymmetry.html':
                source = shared_guide_header(source, strip_managed(sources['index.html']))
                source = re.sub(r'styles\.css\?v=[^"\s]+', 'styles.css?v=20261103-single-nav', source)
            parser = Translator(name, code, translations[code])
            parser.feed(source)
            parser.close()
            translated = ''.join(parser.output)
            translated = re.sub(r'<!-- Generated by scripts/build_columns\.py;.*?-->\s*', '', translated)
            translated = translated.replace('<!doctype html>', '<!doctype html>\n'+MARKER, 1)
            translated = enhance(translated, name, code, translations[code])
            outputs[ROOT/code/name] = translated.replace('\r\n', '\n').encode('utf-8')
    svg = read(ROOT/SVG_SOURCE)
    for code in ('en', 'zh', 'ja'):
        parser = Translator(SVG_SOURCE, code, translations[code])
        parser.feed(svg)
        parser.close()
        outputs[ROOT/f'assets/i18n/{code}/photo-direction.svg'] = ''.join(parser.output).replace('\r\n','\n').encode('utf-8')
    outputs[ROOT/'sitemap.xml'] = sitemap(read(ROOT/'sitemap.xml'), settings).encode('utf-8')
    for code in ('en', 'zh', 'ja'):
        for path in (ROOT/code).rglob('*.html'):
            if path not in outputs and MARKER in read(path):
                raise ValueError(f'Obsolete generated page: {path.relative_to(ROOT)}')
    stale = [path for path, value in outputs.items() if not path.exists() or path.read_bytes() != value]
    if check:
        if stale:
            raise ValueError('Stale multilingual outputs: '+', '.join(str(p.relative_to(ROOT)) for p in stale))
        print('OK: 44 pages, 3 translated diagrams, language links, and sitemap are current (UTF-8).')
        return
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(outputs[path])
    print(f'Built 33 translated pages; updated {len(stale)} files.')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        build(args.check)
        return 0
    except (ValueError, OSError, KeyError, ET.ParseError) as error:
        print(f'Multilingual build failed: {error}', file=sys.stderr)
        return 1

if __name__ == '__main__':
    raise SystemExit(main())
