#!/usr/bin/env python3
"""Build static columns from UTF-8 JSON metadata and HTML body fragments."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from datetime import date
from html import escape
from html.parser import HTMLParser
from pathlib import Path
import json
import re
import sys
from urllib.parse import urlsplit, urlunsplit
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
BASE_URL = "https://k-remedi.com"
CLINIC_ID = BASE_URL + "/#clinic"
STYLESHEET = "/styles.css?v=20261103-single-nav"
COLUMN_STYLESHEET = "/columns.css?v=20261104-first-column"
SOCIAL_IMAGE = BASE_URL + "/assets/main.jpg"
MARKER = "<!-- Generated by scripts/build_columns.py; edit content/columns instead. -->"
REQUIRED_FIELDS = (
    "slug", "title", "description", "published", "modified", "summary", "image", "imageAlt"
)


def read_utf8(path: Path) -> str:
    text = path.read_bytes().decode("utf-8")
    if "\ufffd" in text:
        raise ValueError(f"Replacement character found in {path.relative_to(ROOT)}")
    return text


def root_url(value: str) -> str:
    """Make site-relative asset and page URLs safe at any directory depth."""
    if not value or value.startswith(("#", "//")):
        return value
    parts = urlsplit(value)
    if parts.scheme or parts.netloc:
        return value
    path = "/" + parts.path.lstrip("/")
    if path == "/index.html":
        path = "/"
    elif path.endswith(".html"):
        path = path[:-5]
    return urlunsplit(("", "", path, parts.query, parts.fragment))


def rootify(fragment: str) -> str:
    def replace(match: re.Match[str]) -> str:
        return match[1] + match[2] + root_url(match[3]) + match[2]

    return re.sub(r"(\b(?:href|src)\s*=\s*)([\"'])(.*?)\2", replace, fragment)


def one(pattern: str, text: str, label: str) -> re.Match[str]:
    matches = list(re.finditer(pattern, text, re.DOTALL))
    if len(matches) != 1:
        raise ValueError(f"Expected one {label} in index.html; found {len(matches)}")
    return matches[0]


@dataclass(frozen=True)
class SiteShell:
    before_main: str
    after_main: str
    pixel_loader: str
    shared_meta: str
    graph: list[dict]

    @classmethod
    def load(cls) -> "SiteShell":
        homepage = read_utf8(ROOT / "index.html")
        before = one(r"<body\b[^>]*>(.*?)<main\b[^>]*>", homepage, "body/main opening")[1]
        after = one(r"</main>(.*?)</body>", homepage, "main/body closing")[1]
        loader = one(
            r'<script\b[^>]*\bsrc=["\']meta-pixel\.js[^"\']*["\'][^>]*>\s*</script>',
            homepage, "Meta Pixel loader",
        )[0]
        if len(re.findall(r"facebook\.com/tr\?", before)) != 1:
            raise ValueError("Expected one Meta Pixel noscript fallback before main")
        if "site-header--single" not in before:
            raise ValueError("index.html no longer has the approved single-row header")
        shared_meta = []
        for name in ("facebook-domain-verification", "naver-site-verification", "theme-color"):
            shared_meta.append(one(
                rf'<meta\b[^>]*\bname=["\']{name}["\'][^>]*>', homepage, name
            )[0])
        shared_meta.append(one(r'<link\b[^>]*\brel="icon"[^>]*>', homepage, "favicon")[0])
        structured = json.loads(one(
            r'<script type="application/ld\+json">(.*?)</script>', homepage, "JSON-LD"
        )[1])
        graph = [node for node in structured["@graph"] if node.get("@id") in (
            CLINIC_ID, BASE_URL + "/#website"
        )]
        if len(graph) != 2:
            raise ValueError("Expected the existing clinic and website identities in index.html")
        return cls(rootify(before), rootify(after), rootify(loader), "\n    ".join(shared_meta), graph)


@dataclass(frozen=True)
class Column:
    metadata: dict[str, str]
    body: str

    @property
    def url(self) -> str:
        return BASE_URL + "/columns/" + self.metadata["slug"]

    @property
    def path(self) -> Path:
        return ROOT / "columns" / (self.metadata["slug"] + ".html")


def load_columns() -> list[Column]:
    columns = []
    for path in sorted((ROOT / "content" / "columns").glob("*.json")):
        data = json.loads(read_utf8(path))
        for field in REQUIRED_FIELDS:
            if not isinstance(data.get(field), str) or not data[field].strip():
                raise ValueError(f"{path.name}: {field} must be a nonempty string")
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", data["slug"]) or data["slug"] != path.stem:
            raise ValueError(f"{path.name}: slug must match its filename and use lowercase URL-safe words")
        for field in ("published", "modified"):
            if date.fromisoformat(data[field]).isoformat() != data[field]:
                raise ValueError(f"{path.name}: {field} must be YYYY-MM-DD")
        if data["modified"] < data["published"]:
            raise ValueError(f"{path.name}: modified cannot precede published")
        image = data["image"]
        if not image.startswith("/") or image.startswith("//") or ".." in image.split("/"):
            raise ValueError(f"{path.name}: image must be a root-relative local path")
        if not (ROOT / image.lstrip("/")).is_file():
            raise ValueError(f"{path.name}: image does not exist: {image}")
        body = read_utf8(path.with_suffix(".body.html"))
        if not body.strip() or re.search(r"<(?:html|head|body|main|h1|script)\b", body, re.I):
            raise ValueError(f"{path.name}: body must be a nonempty article fragment without a second H1 or scripts")
        columns.append(Column(data, rootify(body)))
    if not columns:
        raise ValueError("No column metadata found in content/columns/*.json")
    return sorted(columns, key=lambda column: (column.metadata["published"], column.metadata["slug"]), reverse=True)


def check_obsolete_outputs(columns: list[Column]) -> None:
    """Report removed/renamed sources without silently deleting published pages."""
    expected_paths = {column.path for column in columns}
    obsolete = [str(path.relative_to(ROOT)) for path in (ROOT / "columns").glob("*.html")
                if path not in expected_paths and MARKER in read_utf8(path)]
    expected_urls = {column.url for column in columns}
    sitemap = ET.fromstring(read_utf8(ROOT / "sitemap.xml"))
    obsolete.extend(node.text for node in sitemap.findall(".//{*}loc")
                    if node.text and node.text.startswith(BASE_URL + "/columns/")
                    and node.text not in expected_urls)
    if obsolete:
        raise ValueError("Removed or renamed column sources still have published outputs; review the old HTML and sitemap entries: " + ", ".join(obsolete))


class SourceLinks(HTMLParser):
    """Only explicit reference sections supply Article citation URLs."""

    def __init__(self) -> None:
        super().__init__()
        self.sections: list[bool] = []
        self.urls: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes = dict(attrs)
        if tag == "section":
            self.sections.append("column-sources" in (attributes.get("class") or "").split()
                                 or bool(self.sections and self.sections[-1]))
        if tag == "a" and self.sections and self.sections[-1]:
            url = attributes.get("href") or ""
            parts = urlsplit(url)
            if parts.scheme in ("http", "https") and parts.netloc not in ("k-remedi.com", "www.k-remedi.com"):
                if url not in self.urls:
                    self.urls.append(url)

    def handle_endtag(self, tag: str) -> None:
        if tag == "section" and self.sections:
            self.sections.pop()


def breadcrumb_schema(items: list[tuple[str, str]], canonical: str) -> dict:
    return {
        "@type": "BreadcrumbList", "@id": canonical + "#breadcrumb",
        "itemListElement": [
            {"@type": "ListItem", "position": position, "name": name, "item": url}
            for position, (name, url) in enumerate(items, 1)
        ],
    }


def breadcrumb_html(title: str | None = None) -> str:
    current = escape(title) if title else "안면비대칭 칼럼"
    middle = '<li><a href="/columns">안면비대칭 칼럼</a></li>' if title else ""
    return (
        '<nav class="column-breadcrumb" aria-label="현재 위치"><ol>'
        '<li><a href="/">홈</a></li>' + middle +
        '<li aria-current="page">' + current + '</li></ol></nav>'
    )


def page(shell: SiteShell, title: str, description: str, canonical: str,
         content: str, nodes: list[dict], dates: dict | None = None) -> bytes:
    graph = {"@context": "https://schema.org", "@graph": shell.graph + nodes}
    jsonld = json.dumps(graph, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    article_meta = ""
    if dates:
        article_meta = (
            f'\n    <meta property="article:published_time" content="{dates["published"]}" />'
            f'\n    <meta property="article:modified_time" content="{dates["modified"]}" />'
        )
    document = f'''<!doctype html>
{MARKER}
<html lang="ko">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    {shell.shared_meta}
    <title>{escape(title)}</title>
    <meta name="description" content="{escape(description)}" />
    <meta name="robots" content="index, follow, max-image-preview:large" />
    <meta name="author" content="경희 리메디한의원" />
    <link rel="canonical" href="{escape(canonical)}" />
    <meta property="og:type" content="{'article' if dates else 'website'}" />
    <meta property="og:locale" content="ko_KR" />
    <meta property="og:site_name" content="re:medi 한의원" />
    <meta property="og:title" content="{escape(title)}" />
    <meta property="og:description" content="{escape(description)}" />
    <meta property="og:url" content="{escape(canonical)}" />
    <meta property="og:image" content="{SOCIAL_IMAGE}" />{article_meta}
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="{escape(title)}" />
    <meta name="twitter:description" content="{escape(description)}" />
    <meta name="twitter:image" content="{SOCIAL_IMAGE}" />
    <link rel="stylesheet" href="{STYLESHEET}" />
    <link rel="stylesheet" href="{COLUMN_STYLESHEET}" />
    <script type="application/ld+json">
{jsonld}
    </script>
    <!-- Meta Pixel -->
    {shell.pixel_loader}
  </head>
  <body>{shell.before_main}<main id="main" class="columns-main">
{content}
    </main>{shell.after_main}</body>
</html>
'''
    return document.encode("utf-8")


def article_page(shell: SiteShell, column: Column) -> bytes:
    data = column.metadata
    content = f'''      <article class="health-column" aria-labelledby="column-title">
        <header class="column-header">
          {breadcrumb_html(data['title'])}
          <p class="eyebrow">안면비대칭 칼럼</p>
          <h1 id="column-title">{escape(data['title'])}</h1>
          <p class="column-summary">{escape(data['summary'])}</p>
          <div class="column-meta">
            <span>작성 <a href="/intro">경희 리메디한의원</a></span>
            <span>게시 <time datetime="{data['published']}">{data['published']}</time></span>
            <span>수정 <time datetime="{data['modified']}">{data['modified']}</time></span>
          </div>
        </header>
        <div class="column-body">
{column.body.rstrip()}
        </div>
        <p class="columns-back"><a href="/columns">안면비대칭 칼럼 목록</a> · <a href="/asymmetry">안면비대칭 원인·진료 안내</a></p>
      </article>'''
    nodes = [
        {
            "@type": "WebPage", "@id": column.url + "#webpage", "url": column.url,
            "name": data["title"], "description": data["description"], "inLanguage": "ko-KR",
            "isPartOf": {"@id": BASE_URL + "/#website"},
            "breadcrumb": {"@id": column.url + "#breadcrumb"},
            "mainEntity": {"@id": column.url + "#article"},
        },
        {
            "@type": "Article", "@id": column.url + "#article", "url": column.url,
            "headline": data["title"], "description": data["description"],
            "datePublished": data["published"], "dateModified": data["modified"],
            "inLanguage": "ko-KR", "mainEntityOfPage": {"@id": column.url + "#webpage"},
            "author": {"@type": "Organization", "@id": CLINIC_ID, "name": "경희 리메디한의원"},
            "publisher": {"@id": CLINIC_ID},
            "image": {"@type": "ImageObject", "url": BASE_URL + data["image"], "description": data["imageAlt"]},
        },
        breadcrumb_schema([
            ("홈", BASE_URL + "/"), ("안면비대칭 칼럼", BASE_URL + "/columns"), (data["title"], column.url)
        ], column.url),
    ]
    references = SourceLinks()
    references.feed(column.body)
    if references.urls:
        nodes[1]["citation"] = references.urls
    return page(shell, data["title"] + " | 리메디 안면비대칭 칼럼", data["description"], column.url, content, nodes, data)


def listing_page(shell: SiteShell, columns: list[Column]) -> bytes:
    cards = []
    for column in columns:
        data = column.metadata
        cards.append(f'''        <article class="column-preview">
          <h2><a href="/columns/{data['slug']}">{escape(data['title'])}</a></h2>
          <p>{escape(data['summary'])}</p>
          <p class="column-meta">수정 <time datetime="{data['modified']}">{data['modified']}</time></p>
          <a href="/columns/{data['slug']}" aria-label="{escape(data['title'])} 읽기">칼럼 읽기</a>
        </article>''')
    content = '''      <header class="columns-header">
        ''' + breadcrumb_html() + '''
        <p class="eyebrow">re:medi columns</p>
        <h1>안면비대칭 칼럼</h1>
        <p>사진과 거울에서 느끼는 얼굴의 좌우 차이부터 상담 전 확인할 점까지, 안면비대칭에 관한 질문을 살펴봅니다.</p>
        <p><a href="/asymmetry">안면비대칭 원인·증상·진료 안내 보기</a></p>
      </header>
      <div class="columns-list">
''' + "\n".join(cards) + '''
      </div>
      <p class="columns-back"><a href="/">리메디 홈으로</a></p>'''
    canonical = BASE_URL + "/columns"
    nodes = [
        {
            "@type": "CollectionPage", "@id": canonical + "#webpage", "url": canonical,
            "name": "안면비대칭 칼럼", "inLanguage": "ko-KR",
            "isPartOf": {"@id": BASE_URL + "/#website"},
            "breadcrumb": {"@id": canonical + "#breadcrumb"},
            "mainEntity": {"@type": "ItemList", "itemListElement": [
                {"@type": "ListItem", "position": position, "url": column.url, "name": column.metadata["title"]}
                for position, column in enumerate(columns, 1)
            ]},
        },
        breadcrumb_schema([("홈", BASE_URL + "/"), ("안면비대칭 칼럼", canonical)], canonical),
    ]
    return page(shell, "안면비대칭 칼럼 | 경희 리메디한의원",
                "안면비대칭과 사진·거울 속 얼굴 차이에 관한 질문을 살펴보고, 원인·증상·진료 안내로 이어집니다.",
                canonical, content, nodes)


def update_sitemap(columns: list[Column]) -> bytes:
    """Replace only generated URLs, retaining every other byte and lastmod."""
    original = read_utf8(ROOT / "sitemap.xml")
    ET.fromstring(original)
    newline = "\r\n" if "\r\n" in original else "\n"
    dates = {BASE_URL + "/columns": max(column.metadata["modified"] for column in columns)}
    dates.update({column.url: column.metadata["modified"] for column in columns})
    seen = set()

    def entry(url: str) -> str:
        return f"<url><loc>{escape(url)}</loc><lastmod>{dates[url]}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>"

    def replace(match: re.Match[str]) -> str:
        node = ET.fromstring(match[0].strip())
        url = node.findtext("loc")
        if url not in dates:
            return match[0]
        if url in seen:
            raise ValueError(f"Duplicate sitemap URL: {url}")
        seen.add(url)
        return match[1] + entry(url)

    updated = re.sub(r"(^[ \t]*)<url>.*?</url>", replace, original, flags=re.MULTILINE | re.DOTALL)
    additions = "".join("  " + entry(url) + newline for url in dates if url not in seen)
    if updated.count("</urlset>") != 1:
        raise ValueError("Expected one sitemap urlset closing tag")
    updated = updated.replace("</urlset>", additions + "</urlset>")
    ET.fromstring(updated)
    return updated.encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report stale generated files without writing anything")
    args = parser.parse_args()
    try:
        shell = SiteShell.load()
        columns = load_columns()
        check_obsolete_outputs(columns)
        outputs = {ROOT / "columns.html": listing_page(shell, columns)}
        outputs.update({column.path: article_page(shell, column) for column in columns})
        outputs[ROOT / "sitemap.xml"] = update_sitemap(columns)
        stale = [path for path, data in outputs.items() if not path.exists() or path.read_bytes() != data]
        if args.check:
            if stale:
                print("Generated files need updating: " + ", ".join(str(path.relative_to(ROOT)) for path in stale))
                return 1
            print(f"OK: {len(columns)} column(s), listing, and sitemap are current (UTF-8).")
            return 0
        for path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(outputs[path])
            print("Wrote " + str(path.relative_to(ROOT)))
        print(f"Built {len(columns)} column(s); {len(stale)} file(s) changed.")
        return 0
    except (OSError, ValueError, KeyError, ET.ParseError) as error:
        print(f"Column build failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
